# ================================================================ 风格样张 1：热气球
def hot_balloon():
    top, bottom, W = -56.0, -8.0, 34.0

    def w(y):
        t = min(1.0, max(0.0, (y - top) / (bottom - top)))
        return max(5.0, W * math.sin(math.pi * t) ** 0.60)

    ys = [top + (bottom - top) * i / 20 for i in range(21)]
    contour = ([(w(y), y) for y in ys]
               + [(10.0, 2.0), (13.0, 8.0), (15.0, 12.0), (14.0, 30.0), (10.0, 34.0),
                  (-10.0, 34.0), (-14.0, 30.0), (-15.0, 12.0), (-13.0, 8.0), (-10.0, 2.0)]
               + [(-w(y), y) for y in reversed(ys)])

    base = CORAL
    parts = [(P.top(contour, -44.0), L(CORAL, 0.16))]
    for f0, f1 in ((0.24, 0.60),):
        for s in (1, -1):
            a = [(s * w(y) * f0, y) for y in ys[:-1]]
            b = [(s * w(y) * f1, y) for y in reversed(ys[:-1])]
            parts.append((a + b, SKY))
            parts.append(([(s * w(y) * f0, y) for y in ys[9:-1]] +
                          [(s * (w(y) * f0 + 2.0), y) for y in reversed(ys[9:-1])], D(SKY, 0.22)))
    parts.append((P.band_y(contour, -6.0, 10.0), D(CORAL, 0.38)))
    bk = P.bottom(contour, 8.0)
    parts.append((bk, BROWN))
    for x in (-11.0, -7.0, -3.0, 1.0, 5.0, 9.0):
        parts.append((P.band_x(bk, x, x + 2.2), L(BROWN, 0.24)))
    parts.append((P.band_y(bk, 8.0, 13.0), D(BROWN, 0.35)))
    strokes = [_ln([(-11.0, -6.0), (-14.4, 11.0)], 1.4, INK),
               _ln([(11.0, -6.0), (14.4, 11.0)], 1.4, INK),
               _ln([(0.0, -6.0), (0.0, 10.0)], 1.2, D(CORAL, 0.5))]
    for y in (-42.0, -28.0, -16.0):
        strokes.append(_ln([(-w(y), y), (-w(y) * 0.55, y + 1.8), (0.0, y + 2.4),
                            (w(y) * 0.55, y + 1.8), (w(y), y)], 1.2, D(CORAL, 0.30)))
    return Prop("hot_balloon_v10", "热气球", 262, CORAL, D(CORAL, 0.62), contour,
                parts=parts, strokes=strokes, band="样张", kind="样张",
                note="参考图同款：裁片平涂 + 吊篮竖条纹 + 绳网")


